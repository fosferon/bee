# Captures the create baseline that test/fixtures/v0_3_0_create_baseline.exs records.
#
# It is run once, against the v0.3.0 tag, on temporary databases only, and its output
# is committed. Later versions compare their keyless creates against it, so a create
# without `:external_key` is pinned to 0.3.0 behaviour.
#
#     git archive v0.3.0 | tar -x -C <checkout>
#     cd <checkout>   # with deps fetched
#     MIX_ENV=test mix run <path to this file> <output file>
#
# Every scenario runs on its own fresh database under System.tmp_dir!/0, so ids come
# from that database's own counter. Timestamps are recorded as captured; the
# comparison helper (test/support/baseline.exs) normalises only the enumerated ones.

defmodule BaselineCapture do
  @prefix "base"

  def scenarios do
    [
      {:plain, [], {"Plain issue", []}},
      {:labels, [], {"Labelled issue", [labels: ["bug", "ui"]]}},
      {:duplicate_labels, [], {"Duplicate labels", [labels: ["dup", "dup", "other"]]}},
      {:nil_label, [], {"Nil label", [labels: ["kept", nil]]}},
      {:empty_string_label, [], {"Empty-string label", [labels: [""]]}},
      {:parent, [{"Parent issue", []}], {"Child issue", [parent: 1]}},
      {:metadata, [], {"With metadata", [metadata: %{"source" => "baseline", "n" => 1}]}},
      {:priority, [],
       {"With priority", [priority: 2, description: "A description", actor: "baseline"]}}
    ]
  end

  def run([out]) do
    captured =
      Enum.map(scenarios(), fn {name, setup, {title, opts}} ->
        {name, capture(setup, title, opts)}
      end)

    term = %{
      bee_version: to_string(Application.spec(:bee, :vsn)),
      prefix: @prefix,
      scenarios: captured
    }

    header = """
    # Generated by test/support/baseline_capture.exs against bee v0.3.0 on temporary
    # databases. Do not edit by hand.
    """

    body =
      inspect(term,
        pretty: true,
        limit: :infinity,
        printable_limit: :infinity,
        charlists: :as_lists
      )

    File.write!(out, header <> body <> "\n")
    IO.puts("wrote #{length(captured)} scenarios to #{out}")
  end

  def run(_), do: raise("usage: mix run baseline_capture.exs <output file>")

  def capture(setup, title, opts) do
    dir = Path.join(System.tmp_dir!(), "bee_baseline_#{System.unique_integer([:positive])}")
    File.mkdir_p!(dir)
    db_path = Path.join(dir, "bee.db")
    name = :"bee_baseline_#{System.unique_integer([:positive])}"

    {:ok, pid} =
      Bee.Repo.start_link(db_path: db_path, prefix: @prefix, jsonl_path: nil, name: name)

    try do
      Enum.each(setup, fn {setup_title, setup_opts} ->
        {:ok, _} = Bee.create(setup_title, setup_opts, name)
      end)

      reply = Bee.create(title, opts, name)
      {:ok, %{id: id}} = reply
      get = Bee.get(id, name)

      record(
        %{inputs: %{title: title, opts: opts, setup: setup}, create: reply, get: get},
        db_path,
        dir,
        "#{@prefix}-#{id}"
      )
    after
      GenServer.stop(pid)
      File.rm_rf!(dir)
    end
  end

  def record(base, db_path, dir, raw_id) do
    {:ok, conn} = Exqlite.Sqlite3.open(db_path)

    try do
      export_path = Path.join(dir, "export.jsonl")
      :ok = Bee.Export.export(conn, export_path)

      export_lines =
        export_path
        |> File.read!()
        |> String.split("\n", trim: true)
        |> Enum.filter(&(Jason.decode!(&1)["id"] == raw_id))

      Map.merge(base, %{
        labels:
          rows(conn, "SELECT issue_id, label FROM issue_labels WHERE issue_id = ?", [raw_id]),
        events: events(conn, raw_id),
        export: Enum.map(export_lines, &Jason.decode!/1),
        export_raw: export_lines
      })
    after
      Exqlite.Sqlite3.close(conn)
    end
  end

  def events(conn, raw_id) do
    conn
    |> rows(
      "SELECT event_type, actor, payload, created_at FROM events " <>
        "WHERE issue_id = ? AND event_type = 'issue.created' ORDER BY id",
      [raw_id]
    )
    |> Enum.map(fn [type, actor, payload, created_at] ->
      %{
        type: type,
        actor: actor,
        fields: Jason.decode!(payload)["fields"],
        created_at: created_at
      }
    end)
  end

  def rows(conn, sql, params) do
    {:ok, stmt} = Exqlite.Sqlite3.prepare(conn, sql)
    :ok = Exqlite.Sqlite3.bind(stmt, params)

    try do
      Stream.repeatedly(fn -> Exqlite.Sqlite3.step(conn, stmt) end)
      |> Enum.take_while(&match?({:row, _}, &1))
      |> Enum.map(fn {:row, row} -> row end)
      |> Enum.sort()
    after
      Exqlite.Sqlite3.release(conn, stmt)
    end
  end
end

BaselineCapture.run(System.argv())
